# src/classification/fix_infrastructure_benchmark.py
#
# Removes the 5 mislabeled "Infrastructure" tickets from
# data/novel_tickets_expanded.json that describe physical-building/
# facilities issues (flickering lights, stuck doors, burst pipes, stuck
# elevator, broken heater) rather than compute/server infrastructure.
#
# ROOT CAUSE: every one of the 9 scenario tuples actually defined for
# "Infrastructure" in generate_dataset.py's SCENARIOS dict is compute/server
# focused (CPU, memory, kubelet, NTP, cron, load balancer, disk I/O,
# autoscaling) -- confirmed by direct inspection. There is no facilities-
# adjacent scenario anywhere in this category. The 5 tickets in question
# were generated by Gemini using the everyday-English sense of
# "infrastructure" rather than this project's specific IT-infrastructure
# scope, and are therefore mislabeled ground truth, not genuine hard
# examples -- no classifier trained on this dataset could reasonably be
# expected to get them right.
#
# This script identifies them by matching on their known distinctive
# substrings (safer than relying on list position, which could silently
# shift if the file is regenerated differently), removes them, and writes
# the corrected 41-ticket benchmark back to the SAME file
# (data/novel_tickets_expanded.json), after printing a full before/after
# summary so nothing is silently dropped without visibility.
#
# Run from the project root:
#     python src/classification/fix_infrastructure_benchmark.py

import os
import sys
import json

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(os.path.dirname(_THIS_DIR))
BENCHMARK_PATH = os.path.join(PROJECT_ROOT, "data", "novel_tickets_expanded.json")

# Distinctive substrings from each of the 5 mislabeled tickets, confirmed
# from the actual misclassification output. Matching on substring (not
# full-text equality) so minor whitespace/formatting differences don't
# cause a silent miss.
MISLABELED_SUBSTRINGS = [
    "flickered and died",                 # lights / lost power to outlets
    "main entrance doors are completely stuck",  # stuck door, dead keycard reader
    "bathroom on the second floor is totally flooded",  # burst pipe
    "elevator in our building is making a really loud grinding noise",  # stuck elevator
    "heater started blowing ice-cold air",  # broken heater/thermostat
]


def main():
    if not os.path.isfile(BENCHMARK_PATH):
        print(f"ERROR: {BENCHMARK_PATH} not found.")
        sys.exit(1)

    with open(BENCHMARK_PATH, "r", encoding="utf-8") as f:
        tickets = json.load(f)

    print(f"Loaded {len(tickets)} tickets from {BENCHMARK_PATH}")

    removed = []
    kept = []
    for t in tickets:
        text = t.get("text", "")
        matched_substring = next(
            (s for s in MISLABELED_SUBSTRINGS if s in text), None
        )
        if matched_substring is not None:
            removed.append((t, matched_substring))
        else:
            kept.append(t)

    print(f"\nIdentified {len(removed)} mislabeled ticket(s) to remove:")
    for t, matched_substring in removed:
        print(f"  - [{t.get('expected')}] matched on {matched_substring!r}")
        print(f"    text: {t.get('text')}")

    if len(removed) != len(MISLABELED_SUBSTRINGS):
        print(
            f"\nWARNING: expected to find exactly {len(MISLABELED_SUBSTRINGS)} "
            f"mislabeled tickets, but found {len(removed)}. Some of the known "
            "substrings did NOT match anything in the current file -- the "
            "file may have already been edited, or the ticket text may "
            "differ from what was expected. Please review the 'removed' "
            "list above carefully before trusting the output."
        )

    print(f"\nKeeping {len(kept)} ticket(s).")

    # Per-category count sanity check, for visibility.
    counts = {}
    for t in kept:
        counts[t["expected"]] = counts.get(t["expected"], 0) + 1
    print("\nPer-category counts AFTER removal:")
    for cat in sorted(counts):
        print(f"  {cat:<20} {counts[cat]}")
    print(f"  {'TOTAL':<20} {len(kept)}")

    with open(BENCHMARK_PATH, "w", encoding="utf-8") as f:
        json.dump(kept, f, indent=2, ensure_ascii=False)

    print(f"\nWrote corrected benchmark ({len(kept)} tickets) back to:\n  {BENCHMARK_PATH}")


if __name__ == "__main__":
    main()