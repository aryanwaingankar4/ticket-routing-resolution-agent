# Cascade execution                                                            #
# --------------------------------------------------------------------------- #
def run_cascade(texts, tier1_vec, tier1_clf, tier2_clf, embedder_or_emb,
                threshold, tier2_emb=None):
    """Run the cascade over `texts`.

    For each ticket: get Tier-1 prediction + confidence. If confidence >=
    threshold -> use Tier-1. Otherwise -> use Tier-2 (embeddings clf).

    `tier2_emb` may be supplied when embeddings for exactly these texts are
    already available (e.g. sliced from the cached full-dataset embeddings);
    otherwise pass an embedder model in `embedder_or_emb` to encode on demand.

    Returns dict with: preds (list), tiers (list of 1/2), tier1_conf (np array),
    n_tier1, n_tier2.
    """
    texts = list(texts)
    t1_preds, t1_conf = get_tier1_confidence(tier1_vec, tier1_clf, texts)

    escalate_idx = np.where(t1_conf < threshold)[0]

    final_preds = list(t1_preds)
    tiers = [1] * len(texts)

    if len(escalate_idx) > 0:
        if tier2_emb is not None:
            esc_emb = tier2_emb[escalate_idx]
        else:
            esc_texts = [texts[i] for i in escalate_idx]
            esc_emb = embedder_or_emb.encode(esc_texts, convert_to_numpy=True)
            esc_emb = np.asarray(esc_emb, dtype=np.float32)
        t2_preds = tier2_clf.predict(esc_emb)
        for k, idx in enumerate(escalate_idx):
            final_preds[idx] = t2_preds[k]
            tiers[idx] = 2

    n_tier2 = int(len(escalate_idx))
    n_tier1 = len(texts) - n_tier2
    return {
        "preds": final_preds,
        "tiers": tiers,
        "tier1_conf": t1_conf,
        "n_tier1": n_tier1,
        "n_tier2": n_tier2,
    }


def validate_novel_labels(training_categories):
    """Ensure every NOVEL_TICKETS expected label matches a real training class.

    Exits with a clear mismatch report if any expected label is unknown.
    """
    known = set(training_categories)
    mismatches = []
    for i, t in enumerate(NOVEL_TICKETS):
        if t["expected"] not in known:
            mismatches.append((i, t["expected"]))
    if mismatches:
        print("[ERROR] NOVEL_TICKETS contains expected labels that do NOT match "
              "any training category:")
        for i, lab in mismatches:
            print(f"        novel ticket #{i}: expected='{lab}' (not in training set)")
        print(f"        Known training categories: {sorted(known)}")
        sys.exit(1)
    print(f"[check] All {len(NOVEL_TICKETS)} novel-ticket labels match real "
          f"training categories.")


def validate_loaded_calibration_labels(calibration_tickets, training_categories):
    """Ensure every loaded calibration-set expected label matches a real training
    class. Mirrors validate_novel_labels.

    Exits with a clear mismatch report if any expected label is unknown - bad
    records are reported, not silently dropped.
    """
    known = set(training_categories)
    mismatches = []
    for i, t in enumerate(calibration_tickets):
        if t["expected"] not in known:
            mismatches.append((i, t["expected"]))
    if mismatches:
        print("[ERROR] The loaded calibration set contains expected labels that "
              "do NOT match any training category:")
        for i, lab in mismatches:
            print(f"        calibration ticket #{i}: expected='{lab}' "
                  f"(not in training set)")
        print(f"        Known training categories: {sorted(known)}")
        print("        Regenerate the calibration set with:")
        print("            python src/classification/generate_calibration_set.py")
        sys.exit(1)
    print(f"[check] All {len(calibration_tickets)} calibration-ticket labels "
          f"match real training categories.")


