# Tier 1: TF-IDF + LogisticRegression                                          #
# --------------------------------------------------------------------------- #
def train_tier1(X_train_text, y_train):
    """Fit the cheap Tier-1 model on the given training text.

    Returns (vectorizer, clf). Matches the project's Tier-A candidate config.
    """
    vectorizer = TfidfVectorizer(
        max_features=5000,
        ngram_range=(1, 2),
        stop_words="english",
    )
    X_train_tfidf = vectorizer.fit_transform(X_train_text)
    clf = LogisticRegression(max_iter=1000)
    clf.fit(X_train_tfidf, y_train)
    return vectorizer, clf


def get_tier1_confidence(vectorizer, clf, texts):
    """Return (predictions, confidences) for Tier 1 over an iterable of texts.

    confidence = max predict_proba over classes for each row.
    """
    X = vectorizer.transform(texts)
    proba = clf.predict_proba(X)
    preds = clf.classes_[np.argmax(proba, axis=1)]
    conf = np.max(proba, axis=1)
    return preds, conf


