def load_and_validate_csv(csv_path: str = CSV_PATH) -> pd.DataFrame:
    """Load the ticket CSV and run the project's standard validation gates."""
    if not os.path.exists(csv_path):
        print(f"[ERROR] Could not find the dataset CSV at:\n        {csv_path}")
        print("        Expected data/synthetic_tickets.csv relative to project root.")
        print("        Run this script from the project root, or generate the dataset first.")
        sys.exit(1)

    try:
        df = pd.read_csv(csv_path)
    except Exception as exc:  # noqa: BLE001
        print(f"[ERROR] Failed to read CSV at {csv_path}: {exc}")
        sys.exit(1)

    # Required columns present.
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        print(f"[ERROR] CSV is missing required columns: {missing}")
        print(f"        Found columns: {list(df.columns)}")
        sys.exit(1)

    # No NaNs in the fields we actually use.
    for col in ["title", "description", "category"]:
        n_nan = df[col].isna().sum()
        if n_nan > 0:
            print(f"[ERROR] Column '{col}' contains {n_nan} NaN value(s). "
                  f"Clean the dataset before training.")
            sys.exit(1)

    # At least MIN_CATEGORIES distinct categories.
    n_cats = df["category"].nunique()
    if n_cats < MIN_CATEGORIES:
        print(f"[ERROR] Expected at least {MIN_CATEGORIES} categories, "
              f"found only {n_cats}: {sorted(df['category'].unique())}")
        sys.exit(1)

    # Stratification sanity check: every class must have >= 2 rows so an 80/20
    # stratified split can place at least one row in each split.
    class_counts = df["category"].value_counts()
    too_small = class_counts[class_counts < 2]
    if len(too_small) > 0:
        print("[ERROR] These categories have fewer than 2 rows and cannot be "
              "stratified into a train/test split:")
        print(too_small.to_string())
        sys.exit(1)

    print(f"[data] Loaded {len(df)} tickets, {n_cats} categories from "
          f"{os.path.relpath(csv_path, PROJECT_ROOT)}")
    print(f"[data] Category balance:\n{class_counts.sort_index().to_string()}")
    return df


