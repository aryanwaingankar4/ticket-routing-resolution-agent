def standard_split(X, y):
    """The one split used everywhere in this project: 80/20, seed 42, stratified.

    Reusing this exact call guarantees the cascade is evaluated on the SAME
    800-row held-out test set that train_embeddings.py used.
    """
    return train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE, stratify=y
    )


