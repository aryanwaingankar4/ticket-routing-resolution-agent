# src/classification/train_cascade.py
"""
Confidence-based CASCADE classifier for IT-support-ticket routing.
================================================================================

WHAT THIS FILE DOES
-------------------
Implements and evaluates a two-tier confidence-based cascade classifier:

    Tier 1 (cheap):     TF-IDF + LogisticRegression. Runs first on EVERY ticket.
    Decision rule:      if Tier 1's predicted-class probability (predict_proba
                        max) >= CASCADE_CONFIDENCE_THRESHOLD -> ACCEPT Tier 1's
                        prediction. Done. No Tier 2 call needed.
    Tier 2 (expensive): sentence-transformers "BAAI/bge-base-en-v1.5"
                        embeddings + LogisticRegression. Only invoked when Tier 1
                        is NOT confident enough; its prediction then overrides
                        Tier 1's.

WHY THIS DESIGN (the "don't guess when uncertain, escalate instead" principle)
------------------------------------------------------------------------------
This mirrors EXACTLY the same philosophy already used one level up in this
project's RAG layer. In src/rag/suggest_resolution.py there is a
SIMILARITY_THRESHOLD = 0.35 guard: when retrieval confidence is too low, the
code REFUSES to guess with the LLM and instead escalates the ticket to a human.

This cascade applies the identical philosophy one level DOWN - at
model-selection time instead of ticket-resolution time. Instead of "retrieval
too weak -> escalate to a human", here it is "cheap model too unsure -> escalate
to the expensive model". Same idea, different layer: never spend an expensive
call (or make a confident-sounding guess) when the cheap/confident path is
untrustworthy.

This is a FrugalGPT-style cascade: route the easy cases through the cheap model
and only pay for the expensive model on the hard cases. Even if end accuracy
does not jump dramatically, the EFFICIENCY win (fraction of traffic served by
the cheap tier) is a first-class result and is reported honestly either way.

CALIBRATION FIRST
-----------------
We do NOT hardcode an arbitrary confidence threshold. We first measure whether
Tier 1's predict_proba is trustworthy (reliability / calibration table), then
DERIVE the threshold from the point where Tier 1's actual accuracy drops below a
stated target band (~90-95%). Classifier probabilities (like LLM confidences)
are frequently over-confident, so we verify empirically rather than taking the
raw score at face value.

IMPORTANT (why we calibrate on a SEPARATE paraphrased set)
-----------------------------------------------------------
The held-out 800-row test split is drawn from the SAME synthetic templates as
training, so Tier-1 (TF-IDF) shows ~100% accuracy in every confidence bucket
there. That in-distribution perfection makes the derivation rule pick an
unreliably-low threshold that fails on real out-of-distribution phrasing. To
fix this we ALSO calibrate on a separate, denser calibration set of plain,
non-template, paraphrased tickets loaded from
data/calibration_tickets_paraphrased.json (175 tickets, 25 per category,
generated by src/classification/generate_calibration_set.py) - and use THAT
derived threshold for the cascade. The held-out-split calibration is still
printed first for comparison, but the calibration-set threshold is the one
actually applied.

NOTE: the loaded calibration set is kept COMPLETELY INDEPENDENT of
NOVEL_TICKETS. NOVEL_TICKETS is used ONLY for final benchmark evaluation and
never for threshold derivation, so the benchmark stays uncontaminated.

TRADEOFF ANALYSIS (accuracy/efficiency bars)
---------------------------------------------
The single-threshold derivation above uses ONE stated accuracy bar
(TIER1_ACCEPT_ACCURACY_TARGET = 0.90). At that 90% bar the calibration set's
confidence distribution may not support any cheap-tier usage at all (threshold
collapses to 1.00, 100% Tier-2). To characterize the tradeoff properly we ALSO
sweep a small set of LOWER accuracy bars (ACCURACY_TARGETS_TO_TEST) and report,
for each, the derived threshold and the resulting Tier-1 usage / accuracy on
both the held-out split and the 14 novel tickets. This turns a single negative
result into a proper accuracy/efficiency tradeoff table for the results section.
Lowering the bar is a legitimate, statable design choice: we accept up to X%
more errors in exchange for Y% fewer expensive-tier calls.
"""

