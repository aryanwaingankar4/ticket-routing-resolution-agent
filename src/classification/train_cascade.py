# shape ("text"/"expected") as NOVEL_TICKETS, so it is a drop-in replacement    #
# wherever the old CALIBRATION_TICKETS list was used.                          #
# --------------------------------------------------------------------------- #
def load_calibration_set(path: str = CALIBRATION_JSON_PATH):
    """Load and validate the paraphrased calibration set from JSON.

    - Requires the file to exist; if it does not, prints a clear message
      explaining it must be generated first, then exits.
    - Loads the JSON list and validates: it is a non-empty list, every record
      has "text" and "expected" keys. (The training-category validation is
      done separately in validate_calibration_labels-style code in main via
      the returned records; see validate_loaded_calibration_labels.)
    - Prints a short load summary: total loaded, per-category counts, and (FYI
      only) how many records are flagged, if a "flagged" key is present.
    - Returns a list of dicts with at least "text" and "expected" (same shape
      as NOVEL_TICKETS).
    """
    if not os.path.exists(path):
        print(f"[ERROR] Calibration set not found at:\n        {path}")
        print("        This file is the ONLY calibration source and must be "
              "generated first.")
        print("        Generate it by running:")
        print("            python src/classification/generate_calibration_set.py")
        sys.exit(1)

    try:
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except Exception as exc:  # noqa: BLE001
        print(f"[ERROR] Failed to read/parse calibration JSON at {path}: {exc}")
        sys.exit(1)

    # Must be a non-empty list.
    if not isinstance(data, list) or len(data) == 0:
        print(f"[ERROR] Calibration JSON at {path} must be a non-empty list of "
              f"records, got: {type(data).__name__} "
              f"(len={len(data) if hasattr(data, '__len__') else 'n/a'}).")
        print("        Regenerate it with:")
        print("            python src/classification/generate_calibration_set.py")
        sys.exit(1)

    # Every record must have "text" and "expected" keys. Do NOT silently drop
    # bad records - report all offenders clearly and exit.
    bad_records = []
    for i, rec in enumerate(data):
        if not isinstance(rec, dict):
            bad_records.append((i, f"record is {type(rec).__name__}, not an object"))
            continue
        missing_keys = [k for k in ("text", "expected") if k not in rec]
        if missing_keys:
            bad_records.append((i, f"missing key(s): {missing_keys}"))
            continue
        if not isinstance(rec["text"], str) or not rec["text"].strip():
            bad_records.append((i, "'text' is empty or not a string"))
            continue
        if not isinstance(rec["expected"], str) or not rec["expected"].strip():
            bad_records.append((i, "'expected' is empty or not a string"))

    if bad_records:
        print(f"[ERROR] Calibration JSON at {path} contains {len(bad_records)} "
              f"malformed record(s) (every record needs non-empty 'text' and "
              f"'expected' keys):")
        for i, why in bad_records:
            print(f"        record #{i}: {why}")
        print("        Regenerate it with:")
        print("            python src/classification/generate_calibration_set.py")
        sys.exit(1)

    # ---- Load summary --------------------------------------------------- #
    per_cat = {}
    for rec in data:
        per_cat[rec["expected"]] = per_cat.get(rec["expected"], 0) + 1
    n_flagged = sum(1 for rec in data if rec.get("flagged"))

    if n_flagged > 0:
        print(f"[calibration] Loaded {len(data)} tickets ({n_flagged} flagged for "
              f"label disagreement, used anyway - ground truth labels are "
              f"unaffected)")
    else:
        print(f"[calibration] Loaded {len(data)} tickets")
    print("[calibration] Per-category counts: " + "  ".join(
        f"{cat}={per_cat[cat]}" for cat in sorted(per_cat)
    ))

    # Return records preserving at least "text"/"expected" (drop-in shape). We
    # keep the full record so an optional "flagged" flag survives if present.
    return list(data)


