"""Evaluate the unchanged pipeline on the author-written independent test set.

Paper revision (Oct 2026), Phase 3. See data/independent_test/GUIDELINES.md.
Two authors, AW and SP, each write about 54 tickets (7 per category + 5
off-topic or vague) and each labels the OTHER's tickets blind. Disagreements
are resolved by discussion. No LLM call, no retraining, no threshold change.

Files (data/independent_test/), exact names:
  tickets_AW.csv, tickets_SP.csv
      ticket_id, author, title, description, true_category,
      expected_outcome, notes            ids AW001..., SP001...
  second_labels_on_AW_by_SP.csv, second_labels_on_SP_by_AW.csv
      ticket_id, title, description, second_label,
      second_expected_outcome, labeller
      generated by --make-second-label-files with the answers hidden
  adjudication.csv
      ticket_id, author_label, second_label, final_label,
      author_outcome, second_outcome, final_outcome, resolved_by, reason
      one row per ticket where the category OR the outcome disagrees;
      --make-adjudication-file pre-fills the author/second columns, and the
      final_* of a field that already agrees with the agreed value

Labels: true_category / second_label / final_label are one of the seven
categories, or NONE. NONE is allowed only with outcome = escalate (an
off-topic ticket), for the writer, the second labeller and the final label
alike; a vague ticket keeps a real category if it has one. Both the
category and the expected outcome are cross-labelled.

Metrics: category accuracy only on rows whose gold category is not NONE;
escalation correctness (escalated vs the gold outcome) on all rows. Cohen's
kappa, for category and for outcome separately, is computed on the first,
independent labels BEFORE adjudication, pooled and per direction, with a
seeded 10,000-draw bootstrap interval.

Modes:
  --check-only                 status report; works with zero, one or both
                               ticket files filled and with second labels
                               missing or partial; loads no model
  --make-second-label-files    write the two blind files from the filled
                               ticket files (shuffled, seed 42, labels empty)
  --make-adjudication-file     write adjudication.csv pre-filled with every
                               disagreement (final_label etc. empty)
  (no flag)                    final run: FATAL unless both ticket files are
                               filled, both second-label files are complete
                               and every disagreement is adjudicated
  --single-annotator           fallback: gold = the writers' labels, kappa
                               skipped; FATAL if any second label is filled.
                               The paper must then say "single annotator".

Outputs (data/independent_test/results/, refuses to overwrite without --force):
  independent_tickets_routed.csv, independent_summary.csv

    .\\venv\\Scripts\\python.exe scripts/eval_independent.py --check-only
    .\\venv\\Scripts\\python.exe scripts/eval_independent.py --make-second-label-files
    .\\venv\\Scripts\\python.exe scripts/eval_independent.py --make-adjudication-file
    .\\venv\\Scripts\\python.exe scripts/eval_independent.py
"""

from __future__ import annotations

import argparse
import csv
import os
import random
import re
from collections import Counter

from realworld_common import PROJECT_ROOT, die, route, summarise, wilson

DIR = os.path.join(PROJECT_ROOT, "data", "independent_test")
DATASET = os.path.join(PROJECT_ROOT, "data", "synthetic_tickets.csv")

AUTHORS = ("AW", "SP")
LABELLER_OF = {"AW": "SP", "SP": "AW"}     # who second-labels whose tickets
NONE = "NONE"
OUTCOMES = ("escalate", "proceed")
PER_CATEGORY, OFF_TOPIC_OR_VAGUE = 7, 5     # the target per author
TICKET_COLS = ["ticket_id", "author", "title", "description",
               "true_category", "expected_outcome", "notes"]
SECOND_COLS = ["ticket_id", "title", "description", "second_label",
               "second_expected_outcome", "labeller"]
ADJ_COLS = ["ticket_id", "author_label", "second_label", "final_label",
            "author_outcome", "second_outcome", "final_outcome",
            "resolved_by", "reason"]
BOOTSTRAP_DRAWS, SEED = 10_000, 42
SINGLE_NOTE = ("SINGLE ANNOTATOR: these labels were assigned by each "
               "ticket's writer alone and no inter-annotator agreement was "
               "measured. The paper must state that the independent set was "
               "labelled by a single annotator.")


def p_tickets(a):
    return os.path.join(DIR, f"tickets_{a}.csv")


def p_second(a):
    return os.path.join(DIR, f"second_labels_on_{a}_by_{LABELLER_OF[a]}.csv")


def p_adj():
    return os.path.join(DIR, "adjudication.csv")


def read(path, cols):
    with open(path, newline="", encoding="utf-8-sig") as fh:
        rdr = csv.DictReader(fh)
        if rdr.fieldnames != cols:
            die(f"{os.path.basename(path)}: columns {rdr.fieldnames}, "
                f"expected {cols}")
        return [{k: (v or "").strip() for k, v in r.items()} for r in rdr]


def write(path, cols, rows, force):
    if os.path.exists(path) and not force:
        die(f"{os.path.basename(path)} exists (use --force to overwrite)")
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(cols)
        w.writerows(rows)
    print(f"[write] {os.path.relpath(path, PROJECT_ROOT)}")


def categories():
    import pandas as pd
    return sorted(pd.read_csv(DATASET)["category"].unique())


def load_tickets(cats):
    """{author: [rows]}; a missing or header-only file gives []."""
    out, seen = {}, set()
    for a in AUTHORS:
        path = p_tickets(a)
        rows = read(path, TICKET_COLS) if os.path.exists(path) else []
        idre = re.compile(rf"^{a}\d{{3}}$")
        for r in rows:
            tid = r["ticket_id"]
            if not idre.match(tid) or r["author"] != a:
                die(f"{os.path.basename(path)}: {tid!r} must be {a}001, "
                    f"{a}002, ... with author {a}")
            if tid in seen:
                die(f"duplicate ticket_id {tid}")
            seen.add(tid)
            if not r["description"]:
                die(f"{tid}: empty description")
            if r["true_category"] not in cats:
                die(f"{tid}: true_category {r['true_category']!r} is not one "
                    f"of {sorted(cats)}")
            if r["expected_outcome"] not in OUTCOMES:
                die(f"{tid}: expected_outcome {r['expected_outcome']!r} is "
                    f"not one of {OUTCOMES}")
            if r["true_category"] == NONE and r["expected_outcome"] != "escalate":
                die(f"{tid}: true_category NONE requires expected_outcome "
                    "escalate")
        out[a] = rows
    return out


def load_second(a, tickets, cats):
    """(labels {id: (category, outcome)}, n_rows, status).

    A row counts as labelled only when BOTH fields are filled; a row with one
    field filled is validated but left out, so the file reads as partial."""
    path = p_second(a)
    if not os.path.exists(path):
        return {}, 0, "missing"
    rows = read(path, SECOND_COLS)
    by_id = {t["ticket_id"]: t for t in tickets}
    ids = [r["ticket_id"] for r in rows]
    if len(set(ids)) != len(ids):
        die(f"{os.path.basename(path)}: duplicate ticket_id")
    if set(ids) != set(by_id):
        die(f"{os.path.basename(path)} covers different ticket ids from "
            f"tickets_{a}.csv: regenerate it with --make-second-label-files "
            "(--force) if no label has been entered yet")
    labels = {}
    for r in rows:
        t = by_id[r["ticket_id"]]
        if (r["title"], r["description"]) != (t["title"], t["description"]):
            die(f"{r['ticket_id']}: text differs from tickets_{a}.csv; the "
                "ticket was edited after the second-label file was made")
        lab, out = r["second_label"], r["second_expected_outcome"]
        if lab and lab not in cats:
            die(f"{r['ticket_id']}: second_label {lab!r} is not one of "
                f"{sorted(cats)}")
        if out and out not in OUTCOMES:
            die(f"{r['ticket_id']}: second_expected_outcome {out!r} is not "
                f"one of {OUTCOMES}")
        if not (lab and out):
            continue
        if lab == NONE and out != "escalate":
            die(f"{r['ticket_id']}: second_label NONE requires "
                "second_expected_outcome escalate")
        if r["labeller"] != LABELLER_OF[a]:
            die(f"{r['ticket_id']}: labeller {r['labeller']!r}, expected "
                f"{LABELLER_OF[a]}")
        labels[r["ticket_id"]] = (lab, out)
    status = "complete" if len(labels) == len(rows) else "partial"
    return labels, len(rows), status


def load_adjudication(cats, disagreements):
    """{id: (final_label, final_outcome)}, validated against the files.

    `disagreements` maps id -> ((author_cat, author_out),
    (second_cat, second_out)). A row counts as resolved only when both
    final_label and final_outcome are filled."""
    if not os.path.exists(p_adj()):
        return {}
    adj = {}
    for r in read(p_adj(), ADJ_COLS):
        tid = r["ticket_id"]
        if tid not in disagreements:
            die(f"adjudication.csv: {tid} is not a disagreement")
        (ac, ao), (sc, so) = disagreements[tid]
        rec = (r["author_label"], r["author_outcome"],
               r["second_label"], r["second_outcome"])
        if rec != (ac, ao, sc, so):
            die(f"adjudication.csv: {tid} records {rec} but the files say "
                f"{(ac, ao, sc, so)}")
        fl, fo = r["final_label"], r["final_outcome"]
        if not (fl and fo):
            continue                      # pre-filled row, not yet resolved
        if fl not in cats:
            die(f"adjudication.csv: {tid} final_label {fl!r}")
        if fo not in OUTCOMES:
            die(f"adjudication.csv: {tid} final_outcome {fo!r}")
        if fl == NONE and fo != "escalate":
            die(f"adjudication.csv: {tid} final_label NONE requires "
                "final_outcome escalate")
        if not r["resolved_by"]:
            die(f"adjudication.csv: {tid} resolved_by is empty")
        adj[tid] = (fl, fo)
    return adj


def _kappa(ia, ib, n_labels):
    """Cohen's kappa from integer-coded labels; nan when it is undefined."""
    import numpy as np
    cm = np.zeros((n_labels, n_labels))
    np.add.at(cm, (ia, ib), 1)
    n = cm.sum()
    po = np.trace(cm) / n
    pe = float(cm.sum(1) @ cm.sum(0)) / (n * n)
    return float("nan") if pe == 1.0 else (po - pe) / (1.0 - pe)


def kappa_report(a, b, name):
    import numpy as np
    from sklearn.metrics import cohen_kappa_score
    a, b = np.asarray(a), np.asarray(b)
    k = float(cohen_kappa_score(a, b))
    labels = sorted(set(a) | set(b))
    ia, ib = np.searchsorted(labels, a), np.searchsorted(labels, b)
    if not (abs(_kappa(ia, ib, len(labels)) - k) <= 1e-12 or k != k):
        die(f"kappa[{name}]: bootstrap implementation disagrees with sklearn")
    rng = np.random.default_rng(SEED)
    boots = []
    for _ in range(BOOTSTRAP_DRAWS):
        idx = rng.integers(0, len(a), len(a))
        kb = _kappa(ia[idx], ib[idx], len(labels))
        if kb == kb:  # skip draws where kappa is undefined
            boots.append(kb)
    lo, hi = ((float(np.percentile(boots, 2.5)),
               float(np.percentile(boots, 97.5))) if boots
              else (float("nan"), float("nan")))
    agree = int((a == b).sum())
    print(f"  kappa[{name}] = {k:.3f}  bootstrap 95% [{lo:.3f}, {hi:.3f}]  "
          f"raw agreement {agree}/{len(a)}")
    return [(f"kappa.{name}", repr(k)), (f"kappa.{name}.boot95_lo", repr(lo)),
            (f"kappa.{name}.boot95_hi", repr(hi)),
            (f"kappa.{name}.agreement", f"{agree}/{len(a)}")]


def composition(a, rows, cats):
    c = Counter(r["true_category"] for r in rows)
    real = [x for x in sorted(cats) if x != NONE]
    esc = sum(r["expected_outcome"] == "escalate" for r in rows)
    print(f"  {a}: {len(rows)} tickets; " +
          ", ".join(f"{x} {c[x]}" for x in real) + f", NONE {c[NONE]}; "
          f"expected escalate {esc}")
    off = [x for x in real if c[x] != PER_CATEGORY]
    if rows and (off or esc != OFF_TOPIC_OR_VAGUE):
        print(f"    [note] target is {PER_CATEGORY} per category and "
              f"{OFF_TOPIC_OR_VAGUE} off-topic/vague (escalate); a deviation "
              "is allowed but is reported")


def make_second_label_files(tickets, force):
    for a in AUTHORS:
        if not tickets[a]:
            print(f"[skip] tickets_{a}.csv has no rows yet")
            continue
        path = p_second(a)
        if os.path.exists(path):
            filled = [r for r in read(path, SECOND_COLS)
                      if r["second_label"] or r["second_expected_outcome"]]
            if filled:
                die(f"{os.path.basename(path)} already has {len(filled)} "
                    "labelled row(s); refusing to overwrite it")
        rows = [[t["ticket_id"], t["title"], t["description"], "", "",
                 LABELLER_OF[a]] for t in tickets[a]]
        random.Random(SEED).shuffle(rows)
        write(path, SECOND_COLS, rows, force)


def main():
    global DIR
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check-only", action="store_true")
    g.add_argument("--make-second-label-files", action="store_true")
    g.add_argument("--make-adjudication-file", action="store_true")
    g.add_argument("--single-annotator", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--dir", default=None,
                    help="read and write another directory (testing only)")
    args = ap.parse_args()
    if args.dir:
        DIR = os.path.abspath(args.dir)

    cats = set(categories()) | {NONE}
    tickets = load_tickets(cats)
    print("[tickets]")
    for a in AUTHORS:
        composition(a, tickets[a], cats)

    if args.make_second_label_files:
        make_second_label_files(tickets, args.force)
        return

    # Second labels, kappa and disagreements: per direction, as far as they go.
    print("[second labels]")
    second, complete = {}, {}
    for a in AUTHORS:
        labels, n, status = load_second(a, tickets[a], cats)
        second.update(labels)
        complete[a] = bool(tickets[a]) and status == "complete"
        print(f"  {os.path.basename(p_second(a))}: {status}"
              + (f" ({len(labels)}/{n} labelled)" if n else ""))
    summary = [("n_tickets", sum(len(v) for v in tickets.values()))]
    summary += [(f"n_tickets.{a}", len(tickets[a])) for a in AUTHORS]

    all_rows = [t for a in AUTHORS for t in tickets[a]]
    if args.single_annotator:
        if second:
            die("--single-annotator given but second labels exist; drop the "
                "flag so kappa is computed")
        if not all_rows:
            die("no tickets to evaluate")
        for t in all_rows:
            t["gold_category"] = t["true_category"]
            t["gold_outcome"] = t["expected_outcome"]
            t["label_source"] = "single_annotator"
        summary.append(("annotation", "single annotator"))
        print(f"\n[NOTE] {SINGLE_NOTE}\n")
    else:
        done = [t for a in AUTHORS if complete[a] for t in tickets[a]]
        if done:
            print("[kappa: first independent labels, before adjudication]")
            for field, key, j in (("category", "true_category", 0),
                                  ("outcome", "expected_outcome", 1)):
                summary += kappa_report([t[key] for t in done],
                                        [second[t["ticket_id"]][j]
                                         for t in done], field)
                for a in AUTHORS:
                    if complete[a]:
                        summary += kappa_report(
                            [t[key] for t in tickets[a]],
                            [second[t["ticket_id"]][j] for t in tickets[a]],
                            f"{field}.on_{a}_by_{LABELLER_OF[a]}")
        mine = {t["ticket_id"]: (t["true_category"], t["expected_outcome"])
                for t in all_rows}
        dis = {tid: (mine[tid], s) for tid, s in second.items()
               if s != mine[tid]}
        n_dis_cat = sum(a[0] != s[0] for a, s in dis.values())
        n_dis_out = sum(a[1] != s[1] for a, s in dis.values())
        adj = load_adjudication(cats, dis)
        open_ = sorted(set(dis) - set(adj))
        print(f"[disagreements] {len(dis)} ticket(s) so far ({n_dis_cat} on "
              f"category, {n_dis_out} on outcome); {len(adj)} resolved, "
              f"{len(open_)} open")
        for tid in open_:
            (ac, ao), (sc, so) = dis[tid]
            print(f"  {tid}: author {ac}/{ao} vs second {sc}/{so}")

        if args.make_adjudication_file:
            if os.path.exists(p_adj()) and adj:
                die("adjudication.csv already has resolved rows; refusing to "
                    "overwrite it")
            rows = []
            for tid in sorted(dis):
                (ac, ao), (sc, so) = dis[tid]
                rows.append([tid, ac, sc, ac if ac == sc else "",
                             ao, so, ao if ao == so else "", "", ""])
            write(p_adj(), ADJ_COLS, rows, args.force)
            return
        if args.check_only:
            todo = [f"tickets_{a}.csv has no rows" for a in AUTHORS
                    if not tickets[a]]
            todo += [f"{os.path.basename(p_second(a))} not complete"
                     for a in AUTHORS if tickets[a] and not complete[a]]
            if open_:
                todo.append(f"{len(open_)} disagreement(s) without a "
                            "final_label and final_outcome")
            print("\n[check-only] nothing routed, nothing written. "
                  + ("Ready for the final run." if not todo
                     else "Not ready: " + "; ".join(todo) + "."))
            return

        for a in AUTHORS:
            if not tickets[a]:
                die(f"tickets_{a}.csv has no rows")
            if not complete[a]:
                die(f"{os.path.basename(p_second(a))} is not complete")
        if open_:
            die("record a final_label and final_outcome for every "
                "disagreement in adjudication.csv first "
                "(--make-adjudication-file)")
        for t in all_rows:
            tid = t["ticket_id"]
            t["gold_category"], t["gold_outcome"] = adj.get(tid, mine[tid])
            t["label_source"] = "resolved" if tid in adj else "agreed"
        # Say what the adjudication file records -- who resolved each row and
        # whose label survived -- not what the guidelines asked for.
        who = Counter(r["resolved_by"] for r in read(p_adj(), ADJ_COLS)
                      if r["ticket_id"] in adj) if adj else Counter()
        summary += [("annotation", "two authors, cross-labelled"),
                    ("disagreements.tickets", len(dis)),
                    ("disagreements.category", n_dis_cat),
                    ("disagreements.outcome", n_dis_out),
                    ("adjudicated", len(adj)),
                    ("adjudicated.final_equals_writer_label",
                     sum(adj[t] == dis[t][0] for t in adj)),
                    ("adjudicated.final_equals_second_label",
                     sum(adj[t] == dis[t][1] for t in adj))]
        summary += [(f"adjudicated.resolved_by.{k}", v)
                    for k, v in sorted(who.items())]

    out_dir = os.path.join(DIR, "results")
    out_tickets = os.path.join(out_dir, "independent_tickets_routed.csv")
    out_summary = os.path.join(out_dir, "independent_summary.csv")
    if os.path.exists(out_summary) and not args.force:
        die(f"Output exists (use --force to overwrite):\n    {out_summary}")

    rows = route([(t["ticket_id"], t["title"], t["description"])
                  for t in all_rows], progress_every=50)
    for r, t in zip(rows, all_rows):
        if r["ticket_id"] != t["ticket_id"]:
            die("row order lost during routing")
        r.update({"author": t["author"], "gold_category": t["gold_category"],
                  "gold_outcome": t["gold_outcome"],
                  "label_source": t["label_source"]})

    with_cat = [r for r in rows if r["gold_category"] != NONE]
    summary.append(("n_with_category", len(with_cat)))
    summary += [(f"with_category.{k}", v)
                for k, v in summarise(with_cat, gold_key="gold_category",
                                      label="with-category")]

    def prop(name, k, n):
        lo, hi = wilson(k, n)
        summary.extend([(f"{name}.k", k), (f"{name}.n", n),
                        (f"{name}.rate", repr(k / n)),
                        (f"{name}.wilson95_lo", repr(lo)),
                        (f"{name}.wilson95_hi", repr(hi))])

    prop("all.escalated", sum(r["escalated"] for r in rows), len(rows))
    prop("all.outcome_correct",
         sum(r["escalated"] == (r["gold_outcome"] == "escalate")
             for r in rows), len(rows))
    esc = [r for r in rows if r["gold_outcome"] == "escalate"]
    pro = [r for r in rows if r["gold_outcome"] == "proceed"]
    if esc:
        prop("should_escalate.escalated", sum(r["escalated"] for r in esc),
             len(esc))
    if pro:
        prop("should_proceed.proceeded",
             sum(not r["escalated"] for r in pro), len(pro))
    prop("all.tier1_kept", sum(int(r["tier"]) == 1 for r in rows), len(rows))

    os.makedirs(out_dir, exist_ok=True)
    with open(out_tickets, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    with open(out_summary, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["quantity", "value"])
        w.writerows(summary)
    for k, v in summary:
        print(f"  {k:<48} {v}")
    if args.single_annotator:
        print(f"\n[NOTE] {SINGLE_NOTE}")
    print(f"[write] {os.path.relpath(out_tickets, PROJECT_ROOT)}")
    print(f"[write] {os.path.relpath(out_summary, PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
