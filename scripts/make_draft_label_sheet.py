"""Build the hand-labelling sheet for the 30 real-ticket drafts.

Paper revision (Oct 2026), Phase 2. Offline, model-free. Reads
data/external_zenodo_7648117/drafts.json (scripts/draft_realworld.py) and
writes, beside it:

  draft_labels.csv         id, grounded, appropriate_handoff, notes
                           one row per draft, labels EMPTY, for AW to fill
  DRAFT_LABELS_README.md   per id: the ticket, its 5 retrieved tickets and
                           the draft, plus the label definitions

Refuses to overwrite either file without --force, and even with --force
refuses to replace a draft_labels.csv that already has a label in it.

    .\\venv\\Scripts\\python.exe scripts/make_draft_label_sheet.py
"""

from __future__ import annotations

import argparse
import csv
import json
import os

from realworld_common import PROJECT_ROOT, die

BASE = os.path.join(PROJECT_ROOT, "data", "external_zenodo_7648117")
DRAFTS = os.path.join(BASE, "drafts.json")
OUT_CSV = os.path.join(BASE, "draft_labels.csv")
OUT_MD = os.path.join(BASE, "DRAFT_LABELS_README.md")
COLS = ["id", "grounded", "appropriate_handoff", "notes"]

HEADER = """\
# Labelling the 30 real-ticket drafts

Generated by `scripts/make_draft_label_sheet.py` from `drafts.json`. Do not
edit this file; fill in **`draft_labels.csv`** (one row per id, same order
as below). The paper reports these labels as **single-annotator** (AW).

Label each draft against **its own retrieved tickets only**. Do not judge
whether the advice would work in general.

| Column | Values | Meaning |
|---|---|---|
| `grounded` | `yes` / `no` | `yes` if every substantive fix step the draft **prescribes** is supported by at least one of the 5 retrieved resolutions (rewording, merging steps, or substituting the ticket's own names is fine). A draft that prescribes no fix and only declines is `yes`. `no` if it prescribes any step that no retrieved resolution supports. |
| `appropriate_handoff` | `yes` / `no` / `na` | Only for drafts that **hand off**, i.e. decline to prescribe a fix and pass the ticket to a person: `yes` if the retrieved tickets really do not fit this ticket, `no` if they did fit and a fix should have been given. `na` if the draft prescribes a fix (a closing "a human should double-check" note on its own is not a hand-off). |
| `notes` | free text | optional |

A draft that prescribes a fix when it should have handed off is captured by
`grounded = no` (an unsupported fix) or by a note.

The routing line under each heading is context only: "mapped" is the team the
source category maps to, "routed" is the team the pipeline chose.

---
"""


def md(text):
    """Escape backslashes so UNC paths render as written in a Markdown preview."""
    return text.replace("\\", "\\\\")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    if os.path.exists(OUT_CSV):
        with open(OUT_CSV, newline="", encoding="utf-8-sig") as fh:
            filled = [r for r in csv.DictReader(fh)
                      if any((r.get(c) or "").strip() for c in COLS[1:])]
        if filled:
            die(f"{OUT_CSV} already has {len(filled)} labelled row(s); "
                "refusing to replace it")
    if any(os.path.exists(p) for p in (OUT_CSV, OUT_MD)) and not args.force:
        die("Outputs exist (use --force to overwrite).")

    with open(DRAFTS, encoding="utf-8") as fh:
        drafts = json.load(fh)["drafts"]
    if len(drafts) != 30 or len({d["ticket_id"] for d in drafts}) != 30:
        die("drafts.json does not hold exactly 30 distinct drafts")

    parts = [HEADER]
    for i, d in enumerate(drafts, start=1):
        parts.append(f"## {i}. id {d['ticket_id']}\n")
        parts.append(f"Source category **{d['source_category']}**; mapped "
                     f"**{d['mapped_category']}**; routed "
                     f"**{d['cascade_category']}** (tier {d['tier']}); top "
                     f"similarity {d['top_similarity']:.4f}\n")
        parts.append("**Ticket**\n")
        parts.append("```text\n" + d["ticket_text"].strip() + "\n```\n")
        parts.append("**Retrieved tickets**\n")
        for r in d["retrieved"]:
            parts.append(f"{r['rank']}. *{r['category']}*, similarity "
                         f"{r['similarity']:.4f}: **{md(r['title'])}**  \n"
                         f"   Description: {md(r['description'])}  \n"
                         f"   Resolution: {md(r['resolution'])}")
        parts.append("\n**Draft**\n")
        parts.append("\n".join("> " + md(line) if line else ">"
                               for line in d["draft"].strip().splitlines()))
        parts.append("\n---\n")

    with open(OUT_MD, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(COLS)
        for d in drafts:
            w.writerow([d["ticket_id"], "", "", ""])
    print(f"[write] {os.path.relpath(OUT_CSV, PROJECT_ROOT)}")
    print(f"[write] {os.path.relpath(OUT_MD, PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
